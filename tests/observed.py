"""The observed errors the tests record, and the table they are written to.

A test that compares against a tolerance calls record_observed() with what it saw,
and the session's end writes the rows into docs/observed-errors-and-tolerances.md,
so a tolerance far from what is observed can be seen and revisited. Shared by the
core tests and the OpenMM plugin's, which both write the one table.
"""
from pathlib import Path

_REPO = Path(__file__).resolve().parent.parent


_OBSERVED_PATH = _REPO / "docs" / "observed-errors-and-tolerances.md"
# Keyed by (test_id, description), not test_id alone: a test that asserts on more
# than one quantity records each separately, and keying on the test alone made the
# last call silently overwrite the earlier ones. Several tests assert an energy
# and then a force under one test id, so half their observations never reached
# the table -- and a tolerance nobody can see is a tolerance nobody revisits.
_observed = {}  # (test_id, description) -> (file, description, tolerance, observed)

_MAX_TEST_ID = 60
_MAX_DESCRIPTION = 60


def record_observed(request, description: str, tolerance: float,
                    observed: float):
    """Record an observed error for auto-generated docs table."""
    test_id = request.node.name
    if len(test_id) > _MAX_TEST_ID:
        raise ValueError(
            f"test_id exceeds {_MAX_TEST_ID} chars: {test_id!r}")
    if len(description) > _MAX_DESCRIPTION:
        raise ValueError(
            f"description exceeds {_MAX_DESCRIPTION} chars: {description!r}")
    fspath = request.node.fspath
    rel = str(Path(fspath).relative_to(_REPO))
    _observed[(test_id, description)] = (rel, description, tolerance, observed)


def _fmt_float(x: float) -> str:
    """Uniform scientific notation: 1 digit before dot, 1 after, e.g. 4.2e-05."""
    return f"{x:.1e}"


def write_observed_docs():
    """Write what this session recorded into the table, keeping the rows of tests
    that did not run. Nothing when the tree has no docs/: the plugin's source tree
    does not carry the table, and its tests run there all the same."""
    if not _observed or not _OBSERVED_PATH.parent.is_dir():
        return

    # Load existing entries (preserves results from tests not run this session).
    # Format: (test_id, description) -> (file, description, tolerance, observed)
    existing = {}
    if _OBSERVED_PATH.exists():
        current_file = None
        for line in _OBSERVED_PATH.read_text().splitlines():
            if line.startswith("## `"):
                current_file = line[4:].rstrip("`").strip()
            elif line.startswith("| `"):
                parts = [p.strip() for p in line.split("|")]
                # parts: ['', '`test_id`', 'desc', 'tol', 'obs', '']
                if len(parts) >= 6:
                    tid = parts[1].strip("`")
                    existing[(tid, parts[2])] = (
                        current_file or "", parts[2], parts[3], parts[4])

    # Upsert entries from this session.
    for key, (fpath, desc, tol, obs) in _observed.items():
        existing[key] = (fpath, desc, _fmt_float(tol), _fmt_float(obs))

    # Group by file, sort files and rows within each file.
    from collections import defaultdict
    by_file = defaultdict(dict)
    for key, (fpath, desc, tol, obs) in existing.items():
        by_file[fpath][key] = (desc, tol, obs)

    # Fixed column widths (from max input limits) for diff-friendly output.
    w_id = _MAX_TEST_ID + 2  # +2 for backticks
    w_desc = _MAX_DESCRIPTION
    w_tol = 9   # "Tolerance" / "1.0e-06"
    w_obs = 8   # "Observed" / "4.2e-05"

    def fmt_row(c1, c2, c3, c4):
        return (f"| {c1:<{w_id}} | {c2:<{w_desc}} "
                f"| {c3:<{w_tol}} | {c4:<{w_obs}} |")

    header_row = fmt_row("Test", "Description", "Tolerance", "Observed")
    sep_row = fmt_row("-" * w_id, "-" * w_desc, "-" * w_tol, "-" * w_obs)

    lines = [
        "# Observed errors and tolerances",
        "",
        "Auto-generated by test runs. Do not edit manually.",
        "If column size changes, review with `git diff -w` to ignore whitespace changes.",
        "",
    ]
    for fpath in sorted(by_file.keys()):
        rows = by_file[fpath]
        lines.append(f"## `{fpath}`")
        lines.append("")
        lines.append(header_row)
        lines.append(sep_row)
        for (tid, _key_desc), (desc, tol, obs) in sorted(
                rows.items(), key=lambda x: (x[1][0], x[0][0])):
            lines.append(fmt_row(f"`{tid}`", desc, tol, obs))
        lines.append("")
    _OBSERVED_PATH.write_text("\n".join(lines))
